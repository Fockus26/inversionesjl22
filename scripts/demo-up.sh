#!/usr/bin/env bash
# Starts the demo copy (docker-compose.demo.yml) and, the first time, installs WordPress and
# WooCommerce, activates the site plugin and seeds invented data (scripts/demo/seed.php).
# The demo accounts' passwords are generated here and written to .env.demo.local (gitignored).
set -euo pipefail
cd "$(dirname "$0")/.."

# --env-file /dev/null: not the project's .env (compose reads it by default).
compose=(docker compose --env-file /dev/null -f docker-compose.demo.yml)
wp() { "${compose[@]}" --profile cli run --rm -T wpcli wp "$@"; }
port="${DEMO_PORT:-8090}"
url="http://localhost:${port}"

"${compose[@]}" up -d --wait db wordpress mailpit

# The wordpress container copies core into the volume on its first request.
for _ in $(seq 1 60); do
  curl -fsS -o /dev/null "${url}/wp-includes/images/blank.gif" 2>/dev/null && break
  sleep 2
done

if wp core is-installed 2>/dev/null; then
  echo "Demo ya instalada: ${url}/wp-admin (cuentas en .env.demo.local)"
  exit 0
fi

pass() { od -An -N15 -tx1 /dev/urandom | tr -d ' \n'; }
admin_pass="$(pass)"; storage_pass="$(pass)"; seo_pass="$(pass)"

wp core install --url="${url}" --title="Tienda demo" --admin_user=demo-admin \
  --admin_password="${admin_pass}" --admin_email=admin@example.com --skip-email
wp language core install es_CO --activate
wp option update timezone_string America/Bogota
wp plugin install woocommerce --activate
wp language plugin install woocommerce es_CO
# The site runs WooCommerce on posts storage, like production; the plugin hooks edit.php.
wp option update woocommerce_custom_orders_table_enabled no
wp option update woocommerce_onboarding_profile '{"skipped":true}' --format=json
wp option update woocommerce_currency COP
wp option update woocommerce_default_country CO:NSA
wp option update woocommerce_price_num_decimals 0
wp option update woocommerce_price_thousand_sep .
wp option update woocommerce_price_decimal_sep ,
# Open store: without it WooCommerce marks a new site "coming soon" in the admin bar.
wp option update woocommerce_coming_soon no
wp plugin activate inversionesjl22-site
# On a site they run on the first admin visit; here now. The roles (004) come from them.
wp eval 'print_r( inversionesjl22_site_run_migrations() );' --user=demo-admin

wp user create demo-bodega bodega@example.com --role=storage_manager \
  --user_pass="${storage_pass}" --first_name=Bodega --display_name="Bodega (demo)"
wp user create demo-seo seo@example.com --role=seo_manager \
  --user_pass="${seo_pass}" --first_name=SEO --display_name="SEO (demo)"
for u in demo-admin demo-bodega demo-seo; do
  wp user meta update "$u" locale es_CO >/dev/null
done

wp eval-file /demo/seed.php

umask 077
cat > .env.demo.local <<EOF
# Demo copy (docker-compose.demo.yml): invented data, generated by scripts/demo-up.sh
DEMO_URL=${url}
DEMO_ADMIN_USER=demo-admin
DEMO_ADMIN_PASSWORD=${admin_pass}
DEMO_STORAGE_USER=demo-bodega
DEMO_STORAGE_PASSWORD=${storage_pass}
DEMO_SEO_USER=demo-seo
DEMO_SEO_PASSWORD=${seo_pass}
EOF

echo "Demo lista: ${url}/wp-admin (cuentas en .env.demo.local)"
